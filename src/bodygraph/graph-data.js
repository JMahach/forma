export const GATES = Object.entries(gatePositions).flatMap(([center, gates]) =>
  gates.map(([id, x, y]) => ({
    id, center, x, y, name: gateThemes[id - 1][0],
    summary: `В рамках Human Design: ${gateThemes[id - 1][1]}`,
  })),
).sort((a, b) => a.id - b.id);

export const getGate = (id) => GATES.find((gate) => gate.id === Number(id));
export const getCenter = (id) => CENTERS.find((center) => center.id === id);

// All paths are original cubic curves, designed in this project's 640 × 820 space.
function channel(a, b, name, controls) {
  const start = getGate(a), end = getGate(b);
  const control = controls || [
    start.x + (end.x - start.x) / 3, start.y + (end.y - start.y) / 3,
    start.x + (end.x - start.x) * 2 / 3, start.y + (end.y - start.y) * 2 / 3,
  ];
  // Additional control pairs form a continuous multi-segment cubic route.
  const points = [[start.x, start.y], ...Array.from({ length: control.length / 2 }, (_, i) => control.slice(i * 2, i * 2 + 2)), [end.x, end.y]];
  const curves = [];
  for (let i = 1; i < points.length; i += 3) curves.push(points.slice(i - 1, i + 3));
  return {
    id: [a, b].sort((x, y) => x - y).join('-'), gates: [a, b], name, curve: curves[0], curves,
    path: `M ${start.x} ${start.y} ${curves.map(curve => `C ${curve.slice(1).flat().join(' ')}`).join(' ')}`,
  };
}

